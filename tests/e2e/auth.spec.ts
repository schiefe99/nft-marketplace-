import { addToCart, expect, go, login, open, test, USERS } from './fixtures'

test.describe('Conta e sessão', () => {
  test('cadastro com validação e conflito de e-mail @mobile', async ({ page }) => {
    await open(page, '/cadastro')
    const dialog = page.getByRole('dialog')
    await dialog.getByRole('button', { name: 'Criar conta' }).click()
    await expect(dialog.getByLabel('Nome de usuário')).toHaveAttribute('aria-invalid', 'true')
    await expect(dialog.getByLabel('Nome de usuário')).toBeFocused()
    await dialog.getByLabel('Nome de usuário').fill('novo_user')
    await dialog.getByLabel('E-mail').fill(USERS.ana.email)
    await dialog.getByLabel('Senha', { exact: true }).fill('Abcdef12')
    await dialog.getByLabel('Confirmar senha').fill('Abcdef12')
    await dialog.getByRole('button', { name: 'Criar conta' }).click()
    await expect(dialog.getByText('Este e-mail já está cadastrado.')).toBeVisible()
    await dialog.getByLabel('E-mail').fill('novo@nft.test')
    await dialog.getByRole('button', { name: 'Criar conta' }).click()
    await expect(page.getByRole('dialog')).toBeHidden()
    // sessão recuperável após refresh
    await page.goto('/conta/perfil')
    await page.reload()
    await expect(page.getByLabel('E-mail *')).toHaveValue('novo@nft.test')
  })

  test('cadastro com nome real persiste mesmo com outra aba gravando no banco', async ({ page }) => {
    await open(page, '/')
    // outra aba aberta antes do cadastro (tem o banco antigo em memória)
    const other = await page.context().newPage()
    await go(other, '/')

    await go(page, '/cadastro')
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('Nome de usuário').fill('Nícolas Martínez')
    await expect(dialog.getByText('Seu @usuário será: nicolas.martinez')).toBeVisible()
    await dialog.getByLabel('E-mail').fill('nicolas@nft.test')
    await dialog.getByLabel('Senha', { exact: true }).fill('Senha1234')
    await dialog.getByLabel('Confirmar senha').fill('Senha1234')
    await dialog.getByRole('button', { name: 'Criar conta' }).click()
    await expect(page.getByRole('dialog')).toBeHidden()

    // a outra aba grava no banco (carrinho) — não pode apagar a conta nova
    await addToCart(other, 'nft-003')
    const saved = await other.evaluate(() => JSON.parse(localStorage.getItem('nft-mock-db')!).users.find((u: { email: string }) => u.email === 'nicolas@nft.test'))
    expect(saved).toMatchObject({ name: 'Nícolas Martínez', username: 'nicolas.martinez' })

    // sai e entra de novo com a conta criada
    await page.evaluate(() => localStorage.removeItem('nft-app-session'))
    await go(page, '/login')
    const login = page.getByRole('dialog')
    await login.getByLabel('E-mail').fill('nicolas@nft.test')
    await login.getByLabel('Senha', { exact: true }).fill('Senha1234')
    await login.getByRole('button', { name: 'Entrar' }).click()
    await expect(page.getByRole('dialog')).toBeHidden()
  })

  test('card de entrar fecha mesmo vindo de página privada', async ({ page }) => {
    await open(page, '/pagamento')
    await expect(page).toHaveURL(/\/login\?redirect=/)
    await page.getByRole('dialog').getByRole('button', { name: 'Fechar' }).click()
    await expect(page).toHaveURL(/\/carrinho$/)
    await go(page, '/conta/perfil')
    await page.getByRole('dialog').getByRole('button', { name: 'Fechar' }).click()
    await expect(page.getByRole('dialog')).toBeHidden()
    await expect(page).toHaveURL(/\/$/)
  })

  test('login inválido, retorno ao fluxo anterior e logout', async ({ page }) => {
    await open(page, '/conta/carteiras')
    await expect(page).toHaveURL(/\/login\?redirect=/)
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('E-mail').fill(USERS.ana.email)
    await dialog.getByLabel('Senha', { exact: true }).fill('errada123')
    await dialog.getByRole('button', { name: 'Entrar' }).click()
    await expect(dialog.getByRole('alert').filter({ hasText: 'E-mail ou senha incorretos.' })).toBeVisible()
    await dialog.getByLabel('Senha', { exact: true }).fill(USERS.ana.password)
    await dialog.getByRole('button', { name: 'Entrar' }).click()
    await expect(page).toHaveURL(/\/conta\/carteiras/)
    await page.getByTestId('logout').click()
    await expect(page).toHaveURL('/')
    await page.goto('/conta/perfil')
    await expect(page).toHaveURL(/\/login/)
  })

  test('expiração de sessão durante a navegação preserva o contexto', async ({ page }) => {
    await open(page, '/')
    await login(page, 'ana')
    await page.goto('/conta/perfil')
    await expect(page.getByLabel('E-mail *')).toHaveValue(USERS.ana.email)
    await page.evaluate(() => window.__mocks!.expireSessions())
    await page.getByRole('link', { name: 'Carteiras' }).first().click()
    await expect(page).toHaveURL(/\/login\?.*reason=expired/)
    await expect(page.getByTestId('session-expired-notice')).toBeVisible()
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('E-mail').fill(USERS.ana.email)
    await dialog.getByLabel('Senha', { exact: true }).fill(USERS.ana.password)
    await dialog.getByRole('button', { name: 'Entrar' }).click()
    await expect(page).toHaveURL(/\/conta\/carteiras/)
  })

  test('troca de usuário limpa dados privados (favoritos e carteiras)', async ({ page }) => {
    await open(page, '/')
    await login(page, 'ana')
    await page.goto('/conta/carteiras')
    await expect(page.getByLabel('Apelido da carteira *').first()).toHaveValue('Principal')
    await expect(page.getByLabel('Endereço da carteira *').first()).toHaveValue(/^0x71C7/)
    await page.getByTestId('logout').click()
    await login(page, 'bruno')
    await page.goto('/conta/carteiras')
    await expect(page.getByLabel('Endereço da carteira *').first()).toHaveValue(/^0x2546/)
    await page.goto('/favoritos')
    // Bruno tem 1 favorito; os favoritos da Ana (Sage Nomad, Golden Beat…) não aparecem
    await expect(page.getByTestId('nft-card')).toHaveCount(1)
    await expect(page.getByText('Sage Nomad #009')).toHaveCount(0)
  })
})
